# 2. Operators
a=10
b=5

#Arithmetic Operators
print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a//b)
print(a%b)
print(a**b)

#Comparision Operators
print(a>b)
print(a<b)
print(a==b)
print(a!=b)

#Logical Operators
print(a>5 and b<10)
print(a>15 or b<10)
print(not(a>b))

